"""SS-03B — what the authoritative Python engine produces for every expected run and plan of the 27 golden fixtures,
for the frontend's cross-engine comparison (the browser engine on the same canonical documents and the same inputs).

These files hold NO expectation of their own: they are the Python engine's output, regenerated from the code. The golden
fixtures are only read and are never changed. The backend's own tests prove these results against the fixtures.

    uv run python scripts/export_survey_python_results.py           # write
    uv run python scripts/export_survey_python_results.py --check   # fail if the committed files have drifted
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from app.domain.survey.callplan import assemble  # noqa: E402
from app.domain.survey.execution import execute, execute_inputs  # noqa: E402
from tests.survey_fixtures import FIXTURE_DIR, load_all, to_bundle  # noqa: E402

OUT = FIXTURE_DIR.parent / "python-results"
RUN_KEYS = (
    "status", "terminal", "pending", "policy_unresolved", "asked", "delivered", "modules", "evidence_states",
    "events", "rejections",
)  # fmt: skip


def export_one(fx: dict[str, Any]) -> dict[str, Any]:
    bundle = to_bundle(fx)
    runs = []
    for run in fx["expected_runs"]:
        facts = run.get("profile") or run.get("facts") or {}
        bad: dict[str, list[dict[str, Any]]] = {}
        for b in run.get("rejected") or []:
            bad.setdefault(b["at"], []).append(b)

        def supplier(key: str, attempt: int, run: dict[str, Any] = run, bad: dict[str, Any] = bad) -> Any:
            refused = bad.get(key, [])
            if attempt < len(refused):
                return refused[attempt]["answer"]
            return run["answers"].get(key) if attempt == len(refused) else None

        live = execute(bundle, facts, supplier)
        # the ordered inputs a simulation would hold: refused answers included, in the order they were given
        inputs = [{"key": e["key"], "answer": e["answer"]} for e in live["events"] if e["kind"] in ("ANSWER", "REJECT")]
        replayed = execute_inputs(bundle, facts, inputs)
        assert all(replayed[k] == live[k] for k in RUN_KEYS), run["name"]
        runs.append({"name": run["name"], "facts": facts, "inputs": inputs, "run": {k: live[k] for k in RUN_KEYS}})
    plans = [
        {"name": p["name"], "facts": p.get("facts") or {}, "plan": assemble(bundle, p.get("facts") or {})}
        for p in fx.get("expected_plans") or []
    ]
    return {
        "source_fixture": fx["fixture"],
        "note": "Generated by Call360-backend from the Python engine. Not an expectation. Do not edit by hand.",
        "runs": runs,
        "plans": plans,
    }


def main() -> int:
    check = "--check" in sys.argv[1:]
    drift = []
    OUT.mkdir(exist_ok=True)
    wanted = set()
    counts = [0, 0]
    for fx in load_all():
        name = f"{fx['fixture']}.python.json"
        wanted.add(name)
        one = export_one(fx)
        counts[0] += len(one["runs"])
        counts[1] += len(one["plans"])
        text = json.dumps(one, indent=1, sort_keys=True, ensure_ascii=False) + "\n"
        path = OUT / name
        if check:
            if not path.exists() or path.read_text() != text:
                drift.append(name)
        else:
            path.write_text(text)
    extra = sorted(p.name for p in OUT.glob("*.python.json") if p.name not in wanted)
    if check:
        if drift or extra:
            print(f"Python engine results have drifted: {drift + extra}")
            return 1
        print(f"Python engine results match ({len(wanted)} files, {counts[0]} runs, {counts[1]} plans)")
        return 0
    print(
        f"Wrote {len(wanted)} files ({counts[0]} runs, {counts[1]} plans) to {OUT.relative_to(FIXTURE_DIR.parents[3])}"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
